static esp_err_t send_cmd(uint8_t cmd) {
    uint8_t data[2] = {0x00, cmd};
    return i2c_master_write_to_device(_i2c_num, SH1107_I2C_ADDR, data, 2, pdMS_TO_TICKS(10));
}

void sh1107_init(i2c_port_t i2c_num) {
    _i2c_num = i2c_num;
    vTaskDelay(pdMS_TO_TICKS(50));

    send_cmd(0xAE); // Display OFF
    send_cmd(0xDC); // Display start line = 0
    send_cmd(0x00);
    send_cmd(0x81); // Contrast
    send_cmd(0x80);
    send_cmd(0xA4); // Normal display mode
    send_cmd(0xA6); // Not inverted
    send_cmd(0xAF); // Display ON
    sh1107_clear();
}

void sh1107_clear(void) {
    memset(oled_buffer, 0, sizeof(oled_buffer));
}

void sh1107_draw_string(uint8_t page, uint8_t col, const char *str) {
    if (page >= OLED_PAGES) return;
    
    while (*str && col < (OLED_WIDTH - 5)) {
        char c = *str++;
        uint8_t font_idx = 0;
        
        if (c >= '0' && c <= '9') {
            font_idx = (c - '0') + 16; // Corrected offset for digits
        } else if (c >= 'A' && c <= 'Z') {
            font_idx = (c - 'A') + 26; // Corrected offset for uppercase
        } else if (c >= 'a' && c <= 'z') {
            font_idx = (c - 'a') + 26; // Map lowercase to uppercase
        } else {
            font_idx = 0; // Default to space
        }

        for (int i = 0; i < 5; i++) {
            if (col + i < OLED_WIDTH) {
                oled_buffer[page][col + i] = font5x7[font_idx][i];
            }
        }
        col += 6; 
    }
}

void sh1107_refresh(void) {
    for (uint8_t page = 0; page < OLED_PAGES; page++) {
        send_cmd(0xB0 + page);          
        send_cmd(0x00);                 
        send_cmd(0x10);                 

        uint8_t packet[OLED_WIDTH + 1];
        packet[0] = 0x40;               
        memcpy(&packet[1], oled_buffer[page], OLED_WIDTH);
        
        i2c_master_write_to_device(_i2c_num, SH1107_I2C_ADDR, packet, sizeof(packet), pdMS_TO_TICKS(10));
    }
}